"""Builds azkauniverse/questions.json for Term 2 (Green Montessori Grade 4, 2026-2027 S1-T2 Science & Social Studies).
Usage: python3 build.py   (from azkauniverse/scripts/term2)  -> writes ../../questions.json and validates."""
import json, sys, os, collections
from xml.etree import ElementTree as ET
sys.path.insert(0, os.path.dirname(__file__))
import l1_energy, l2_light, l3_moon, l4_eclipse, l5_water_land, l6_ethnic, l7_history, l8_landmarks

LEVELS = [
    ("energy-transformation", "Energy Transformation", "⚡", "sun", l1_energy),
    ("light-and-eye", "Light & the Eye", "👁️", "mercury", l2_light),
    ("moon-phases", "Phases of the Moon", "🌙", "moon", l3_moon),
    ("eclipses", "Solar & Lunar Eclipses", "🌑", "eclipse", l4_eclipse),
    ("lakes-deserts-rivers", "Lakes, Deserts & Rivers", "🏞️", "earth", l5_water_land),
    ("ethnic-groups", "Ethnic Groups in Indonesia", "🎭", "mars", l6_ethnic),
    ("history-of-jakarta", "History of Jakarta", "🏙️", "jupiter", l7_history),
    ("jakarta-landmarks", "Jakarta Landmarks", "🗼", "saturn", l8_landmarks),
]

def validate(levels):
    errs = []
    for lv in levels:
        seen = set()
        for q in lv["questions"]:
            w = "%s: %s" % (lv["id"], (q.get("question") or q.get("prompt") or q.get("front") or "")[:70])
            t = q["type"]
            if t == "mc":
                o = q["options"]
                if not (0 <= q["answer"] < len(o)): errs.append(w + " answer index")
                if len(set(o)) != len(o): errs.append(w + " duplicate options")
                if not (2 <= len(o) <= 4): errs.append(w + " option count %d" % len(o))
                if any(not str(x).strip() for x in o): errs.append(w + " empty option")
            elif t == "fill":
                if q["answer"].lower() not in q["acceptable"]: errs.append(w + " answer not acceptable")
                if "_" not in q["question"]: errs.append(w + " no blank")
            elif t == "match":
                p = q["pairs"]
                if len(p) < 2: errs.append(w + " <2 pairs")
                if len({x["term"] for x in p}) != len(p): errs.append(w + " duplicate term")
                if len({x["match"] for x in p}) != len(p): errs.append(w + " duplicate match")
            elif t == "flashcard":
                if not q["front"] or not q["back"]: errs.append(w + " empty flashcard")
            if q.get("image"):
                try: ET.fromstring(q["image"])
                except Exception as e: errs.append(w + " bad svg " + str(e))
            key = json.dumps({k: v for k, v in q.items() if k not in ("options", "answer", "image")}, sort_keys=True)
            if t == "mc": key += "|" + q["options"][q["answer"]]
            if key in seen: errs.append(w + " DUPLICATE")
            seen.add(key)
    return errs

def main():
    levels = []
    for lid, name, emoji, theme, mod in LEVELS:
        qs, seen = [], set()
        for q in mod.build():
            k = json.dumps({a: b for a, b in q.items() if a not in ("options", "answer", "image")}, sort_keys=True)
            if q["type"] == "mc": k += "|" + q["options"][q["answer"]]
            if k in seen: continue
            seen.add(k); qs.append(q)
        levels.append({"id": lid, "name": name, "emoji": emoji, "planetTheme": theme, "questions": qs, "funFacts": mod.FACTS})
    errs = validate(levels)
    out = {"_comment": "SolarQuest question bank - Term 2. Written for 'GMS Workbook: Science & Social Studies, Upper Elementary, Grade 4 Term 2' (Green Montessori School, 2026/2027): Energy Transformation, Light & the Eye, Phases of the Moon, Solar & Lunar Eclipses, Lakes/Deserts/Rivers, Ethnic Groups in Indonesia, History of Jakarta, Jakarta Landmarks. Generated by azkauniverse/scripts/term2/build.py (original wording; answers authored and validated by code). Question type must be one of: mc | fill | match | flashcard.", "levels": levels}
    path = os.path.join(os.path.dirname(__file__), "..", "..", "questions.json")
    with open(path, "w") as f: json.dump(out, f, ensure_ascii=False, indent=1)
    for lv in levels: print(lv["id"], len(lv["questions"]), dict(collections.Counter(q["type"] for q in lv["questions"])), "imgs", sum(1 for q in lv["questions"] if q.get("image")))
    print("ERRORS:", len(errs)); [print(" ", e) for e in errs[:40]]
    return 1 if errs else 0

if __name__ == "__main__":
    sys.exit(main())
